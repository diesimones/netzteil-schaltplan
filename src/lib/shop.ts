export function itemTotal(it: ShopItem) {
  return it.qty * it.unit;
}

export function shopPartsSum() {
  return SHOP_ITEMS.reduce((s, it) => s + itemTotal(it), 0);
}

export function shopByVendor() {
  const map = new Map<string, ShopItem[]>();
  for (const it of SHOP_ITEMS) {
    const list = map.get(it.vendor) ?? [];
    list.push(it);
    map.set(it.vendor, list);
  }
  return [...map.entries()].sort((a, b) => {
    const sa = a[1].reduce((s, i) => s + itemTotal(i), 0);
    const sb = b[1].reduce((s, i) => s + itemTotal(i), 0);
    return sb - sa;
  });
}

export function shopCsv() {
  const rows = ["Gruppe;Ref;Name;MPN;Menge;Einzel_EUR;Summe_EUR;MwSt;Haendler;Link"];
  for (const it of SHOP_ITEMS) {
    rows.push(
      [it.group, it.ref, it.name, it.mpn, it.qty, it.unit.toFixed(2), itemTotal(it).toFixed(2), it.vat, it.vendor, it.url].join(";"),
    );
  }
  rows.push("");
  rows.push(`Summe Teile brutto;;;${shopPartsSum().toFixed(2)} EUR;;;;Stand ${SHOP_ASOF}`);
  return `${rows.join("\n")}\n`;
}
